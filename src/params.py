"""
Разбор и чистка item_infm_params_text: плоская строка «Ключ Значение …» -> поля документа.

ЗАЧЕМ. Параметры — 975 символов в среднем против 34 в заголовке, и большая часть этого —
шаблон, одинаковый у всех объявлений: «Начальная цена Тип стоимости за услугу Стоимость 500
Услуга … График работы от 28800 … Время работы, с 08:00 … Дни пн Дни вт …». Для BM25 это
двойной вред:
  1) нормировка длины документа (|d|/avgdl) наказывает объявления с длинным прайсом, хотя
     длина создана шаблоном, а не содержанием;
  2) шаблонные слова («стоимость», «услуга», «работа», «время») попадают в словарь с высокой
     df, а частые слова запросов («услуга», «ремонт») получают заниженный idf.
Убрав шаблон, мы одновременно чистим сигнал и получаем РАЗДЕЛЬНЫЕ поля для BM25F: заголовок,
названия услуг из прайса, вид/тип услуги — с разными весами.

КАК. Ключи — закрытый словарь, добытый scripts/discover_param_keys.py (ветвящаяся
вариативность). Список ниже курирован вручную: автоматика выдала 504 кандидата, из них
настоящие ключи — частотная голова, а хвост («Ремонт», «Маникюр», «Москва,») — это ЗНАЧЕНИЯ,
попавшие в кандидаты из-за частоты. Включать их разделителями нельзя: они разрезали бы
значения пополам.

Значение ключа = текст до следующего ключа. Ключ, которого нет в списке, не создаёт границу,
и его текст прилипает к предыдущему значению — поэтому список покрывает всё, что встречается
чаще ~150 раз на 60k объявлений.
"""
from __future__ import annotations

import re

# --- ЦЕННЫЕ ключи: значение несёт смысл услуги и должно попасть в индекс ----------
# kind — категория услуги (совпадает с фильтрами запроса «Вид услуги»/«Тип услуги»:
#        98.2% и 95.4% совпадений с выбранным объявлением, ТЗ §1)
KIND_KEYS = [
    "Вид услуги", "Тип услуги", "Вид товара", "Чем вы занимаетесь",
    "Специальность", "Предмет или специальность", "Направление",
]
# service — конкретные услуги из прайс-листа: самый близкий к запросу текст
SERVICE_KEYS = [
    "Название услуги", "Своя услуга", "Услуга",
    # "Услуги" НЕ ключ: сталкивается со значением «Вид услуги Услуги эвакуатора» (243 случая
    # на 30k) и обнуляет kind. «Услуга» в единственном числе — настоящий ключ прайс-листа.
    "Мероприятия", "Занятия", "Груз", "Производители", "Марка авто",
    "Учебное учреждение", "Вид транспорта", "Кузов",
]
# place — где оказывается услуга. Отдельное поле: это гео-текст, он полезен, но путать его
#         с названием услуги нельзя (иначе «Москва» начнёт матчиться как услуга).
PLACE_KEYS = [
    "Место оказания услуг", "Куда выезжаете", "Где вы оказываете услуги",
    "Место сделки", "Районы", "Метро", "Как вы работаете", "Выезд", "Выезд в",
]

# --- МУСОРНЫЕ ключи: ключ и его значение выбрасываются целиком --------------------
JUNK_KEYS = [
    # прайс и типы стоимости — шаблон, повторяется десятки раз в одном объявлении
    "Начальная цена", "Стоимость", "Тип стоимости за услугу", "Тип стоимости за час",
    "Тип стоимости за единицу", "Тип стоимости за день", "Тип стоимости",
    "Минимальная сумма заказа", "Минимальное время заказа", "Предоплата",
    "Признак предзаполнения прайс листа",
    # расписание
    "График работы от", "График работы до", "График работы, дни недели", "График работы",
    "Время работы, с", "Время работы, до", "Время работы",
    "Время для связи от", "Время для связи до", "Время для связи, с",
    "Время для связи, до", "Время для связи, дни недели", "Время для связи",
    "Рабочие дни", "Дни", "Продолжительность",
    # организационные флаги — у всех примерно одинаковые, различающей силы нет
    "Работа по договору", "Гарантия на работу", "Опыт работы",
    "Работаете с юрлицами и ИП", "Работаете с НДС", "Берёте ли срочные заказы",
    "Выполняю заказы от", "Готов закупить материалы", "Камера наблюдения в ремонтной зоне",
    "Онлайн-показ", "Год окончания", "Дополнительно", "Состояние",
    "Вид объявления", "Ваши клиенты", "Кто оказывает",
    # ВНИМАНИЕ: "Грузчики", "Онлайн", "Гарантия", "Бригада" НЕ мусорные ключи.
    # Они чаще встречаются как ЗНАЧЕНИЯ ("Вид услуги Грузчики, складские услуги"),
    # и как разделители они обнуляли значение предыдущего ценного ключа.
    # Их числовые значения и так отсеиваются проверкой _NUMERIC_VALUE.
    # габариты груза — числа, для текстового матчинга бесполезны
    "Грузоподъёмность", "Высота груза", "Длина груза", "Ширина груза",
]

FIELD_OF: dict[str, str] = {}
for _k in KIND_KEYS:
    FIELD_OF[_k] = "kind"
for _k in SERVICE_KEYS:
    FIELD_OF[_k] = "service"
for _k in PLACE_KEYS:
    FIELD_OF[_k] = "place"
for _k in JUNK_KEYS:
    FIELD_OF[_k] = "junk"

ALL_KEYS = list(FIELD_OF)
FIELDS = ("kind", "service", "place", "other")

# Альтернация ключей, длинные раньше коротких: «Тип услуги» должен выиграть у «Тип»,
# «Время для связи, с» — у «Время для связи». (?<![\w]) / (?![\w]) — границы слова, чтобы
# «Услуга» не срабатывала внутри «Услуги».
_KEY_RE = re.compile(
    r"(?<![\w])(" + "|".join(re.escape(k) for k in
                             sorted(ALL_KEYS, key=lambda k: (-len(k.split()), -len(k)))) + r")(?![\w])"
)
# Значение выбрасывается, если это только числа/время/дата/код дня — смысла в индексе нет.
_NUMERIC_VALUE = re.compile(r"^[\d\s.,:;/–—-]*(?:мин\.?|ч|кг|м|руб\.?|лет|года?|%)?[\d\s.,:;/–—-]*$")
_DAY_CODE = re.compile(r"^(?:пн|вт|ср|чт|пт|сб|вс)$", re.I)


def parse(text: str | None) -> dict[str, str]:
    """
    Разобрать строку параметров в поля.

    Возвращает dict с ключами kind/service/place/other — значения склеены через ' ; '.
    Мусорные ключи и их значения не попадают никуда. Значения неизвестных ключей идут в
    'other' (низкий вес в BM25F: там и полезное, и остатки шаблона).
    """
    out: dict[str, list[str]] = {f: [] for f in FIELDS}
    if not text:
        return {f: "" for f in FIELDS}

    spans = [(m.start(), m.end(), m.group(1)) for m in _KEY_RE.finditer(text)]
    if not spans:
        # Ни одного известного ключа — считаем весь текст слабо-полезным.
        return {"kind": "", "service": "", "place": "", "other": text.strip()}

    # Текст до первого ключа (бывает редко) — в 'other'.
    if spans[0][0] > 0:
        head = text[:spans[0][0]].strip()
        if head:
            out["other"].append(head)

    for i, (a, b, key) in enumerate(spans):
        end = spans[i + 1][0] if i + 1 < len(spans) else len(text)
        value = text[b:end].strip(" ,;.")
        field = FIELD_OF[key]
        if field == "junk":
            continue
        if not value or _NUMERIC_VALUE.match(value) or _DAY_CODE.match(value):
            continue
        out[field].append(value)

    # Дубликаты внутри поля убираем: в прайсе одна и та же услуга повторяется многократно.
    res = {}
    for f in FIELDS:
        seen, uniq = set(), []
        for v in out[f]:
            lv = v.lower()
            if lv not in seen:
                seen.add(lv)
                uniq.append(v)
        res[f] = " ; ".join(uniq)
    return res


def parse_many(texts) -> dict[str, list[str]]:
    """Разбор списка текстов -> dict поле -> список строк (по документам, порядок сохранён)."""
    parsed = [parse(t) for t in texts]
    return {f: [p[f] for p in parsed] for f in FIELDS}
